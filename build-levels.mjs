// Builds src/puzzles.js: a hand-made first level, then generated boards chosen with analyze.mjs.
// Every level is checked: the solver's par matches, and iterated ghost deduction proves it.
import { writeFileSync } from 'node:fs';
import { generateWith, paramsFor } from './src/generator.js';
import { parseBoard } from './src/boards.js';
import { solve } from './src/solver.js';
import { deduceRounds, enc } from './analyze.mjs';
import { splits } from './src/suppose.js';
const MONO = { colors: 1, filters: 0 }, C2 = { colors: 2, filters: 0 }, C2F = { colors: 2, filters: 1 };
const SUPPOSE_HINT = 'New tool: <b>Suppose</b>. No claim here can be proven on its own, so reason by cases. Select the mirror at '
  + 'column 5, row 4 and press Suppose. Now there are two boards: in one that mirror stays, in the other it flips. Make claims '
  + 'in each as usual. A case is closed when it forces 4 flips (in the flip case, the supposed flip counts as one), or when it leaves a target with no light at all (then that '
  + 'case can\'t happen). Close both, and 4 is proven either way.';
const PICKS = [ // [generator level, seed, hint, options (default: one color, no filters)]
  ['hand', ['>../.', '.....', '...o.'], 'One mirror stands between the lamp and the target. Select it, then claim it <b>must flip</b>. The game tests the opposite: if it stayed, could any light reach the target? None could, so the claim is proven.'],
  [2, 28, 'Open mirrors (the faint X) may send light either way, so the dashed light shows everywhere light <i>might</i> go. Look for a target that only one dashed path reaches: the mirrors on that path are forced.'],
  [4, 69, 'You can also claim a mirror <b>must stay</b>, when flipping it would leave a target with no light. A settled mirror sends light only one way, and that can make the next claim provable.'],
  [4, 291, 'Here no flip can be proven at the start. Begin with mirrors that must stay.'],
  [4, 30, 'Busy board? Tap a target: only the light that could still reach it stays bright. Where all of that light squeezes through one mirror, the mirror is forced. Tap the target again to see everything.'], [5, 57, null], [4, 538, null], [6, 201, null], [6, 123, null],
  [8, 190, null], [8, 47, null], [9, 74, null], [10, 101, null], [10, 88, null],
  [11, 544, null], [12, 1312, null],
  [9, 6333, 'Two colors now. A cyan (square) target lights only for cyan light, an amber (round) one only for amber. Tap a target: only light of its own color can feed it.', C2],
  [11, 4669, null, C2], [11, 2697, null, C2], [11, 5400, null, C2],
  [13, 6082, 'A tinted pane is a <b>filter</b>: light of its own color passes straight through, the other color is stopped.', C2F],
  [13, 4331, null, C2F],
  // Expert: the round rule alone stops short; one "Suppose" (proof by cases) finishes the proof.
  [4, 24, SUPPOSE_HINT, MONO, 'cases'],
  [6, 106, 'Which mirror to suppose about? First prove every claim you can. Then tap each target to see only the light '
    + 'that could still reach it. A mirror that every target\'s light runs through is a good choice: whichever way it turns, '
    + 'it changes what all of them can get. If neither '
    + 'case closes, <b>Stop supposing</b> drops both cases and keeps your earlier claims (unproven claims still cost stars).', MONO, 'cases'],
  [6, 11, null, MONO, 'cases'],
  [8, 46, null, MONO, 'cases'],
  [12, 59, null, MONO, 'cases'],
  [13, 85, 'Three targets in this chapter now. The same idea scales: prove what you can, then look for the mirror that all three targets\' light runs through.', MONO, 'cases'],
];
const levels = PICKS.map(([L, seed, hint, opts = MONO, kind]) => {
  const rows = L === 'hand' ? seed : enc(generateWith(seed, { ...paramsFor(L), ...opts, splitters: 0 }).puzzle);
  const g = parseBoard(rows), sol = solve(g), par = sol.moves, d = deduceRounds(g);
  if (kind === 'cases') {
    const s = splits(g, par);
    if (s.provable || !s.good.length) throw new Error(`level ${L}/${seed}: not a one-split level`);
    console.log(`${L}/${seed} ${g.w}x${g.h} par ${par} base ${d.flips} flips; working splits ${s.good.length}`);
    return { par, rows, cases: true, sol: sol.flips, ...(hint ? { hint } : {}) };
  }
  if (d.flips !== par) throw new Error(`level ${L}/${seed}: deduction proves ${d.flips}, par ${par}`);
  console.log(`${L}/${typeof seed === 'number' ? seed : '-'} ${g.w}x${g.h} par ${par} rounds ${d.rounds.map((q) => `${q.flips}f${q.stays}s`).join(' ')}`);
  return { par, rows, ...(hint ? { hint } : {}) };
});
writeFileSync('src/puzzles.js', '// Generated by build-levels.mjs. Every par is the solver\'s exact minimum and is provable by ghost deduction\n// (levels with cases: true need one proof by cases; sol is a best solution, shown at the end).\n'
  + 'export const LEVELS = [\n' + levels.map((l) => '  ' + JSON.stringify(l) + ',').join('\n') + '\n];\n');
