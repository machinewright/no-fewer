// Builds src/puzzles.js: a hand-made first level, then generated boards chosen with analyze.mjs.
// Every level is checked: the solver's par matches, and iterated ghost deduction proves it.
import { writeFileSync } from 'node:fs';
import { generateWith, paramsFor } from './src/generator.js';
import { parseBoard } from './src/boards.js';
import { solve } from './src/solver.js';
import { deduceRounds, enc } from './analyze.mjs';
const PICKS = [ // [generator level, seed, hint]
  ['hand', ['>../.', '.....', '...o.'], 'The light misses the target because of one mirror. Click it to claim it <b>must flip</b>. The game checks the opposite: if it stayed, could light still reach the target? It couldn\'t, so the claim is proven.'],
  [2, 28, 'Mirrors you haven\'t claimed are drawn as an <b>X</b>: until you settle them, light may go either way through them (the dashed light). Claim a flip only when keeping the mirror would leave some target with no light at all, solid or dashed.'],
  [4, 69, 'You can also claim a mirror <b>must stay</b>: flipping it would starve a target. A settled mirror sends light only one way, which can make the next flip provable.'],
  [4, 291, 'Here no flip can be proven at the start. Begin with mirrors that must stay.'],
  [4, 30, null], [5, 57, null], [4, 538, null], [6, 201, null], [6, 123, null],
  [8, 190, null], [8, 47, null], [9, 74, null], [10, 101, null], [10, 88, null],
];
const levels = PICKS.map(([L, seed, hint]) => {
  const rows = L === 'hand' ? seed : enc(generateWith(seed, { ...paramsFor(L), colors: 1, filters: 0, splitters: 0 }).puzzle);
  const g = parseBoard(rows), par = solve(g).moves, d = deduceRounds(g);
  if (d.flips !== par) throw new Error(`level ${L}/${seed}: deduction proves ${d.flips}, par ${par}`);
  console.log(`${L}/${typeof seed === 'number' ? seed : '-'} ${g.w}x${g.h} par ${par} rounds ${d.rounds.map((q) => `${q.flips}f${q.stays}s`).join(' ')}`);
  return { par, rows, ...(hint ? { hint } : {}) };
});
writeFileSync('src/puzzles.js', '// Generated by build-levels.mjs. Every par is the solver\'s exact minimum and is provable by ghost deduction.\n'
  + 'export const LEVELS = [\n' + levels.map((l) => '  ' + JSON.stringify(l) + ',').join('\n') + '\n];\n');
